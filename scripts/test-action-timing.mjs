import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const c={Intl,Date};
for(const name of ['data','core','workflow']) vm.runInNewContext(readFileSync(new URL(`../src/${name}.js`,import.meta.url),'utf8'),c);
const {DEMO_DATA:d,DEMO_CORE:core,DEMO_WORKFLOW:w}=c;
const frozen=JSON.stringify(d), s=core.createSession(d);
const signature={signature:d.people.P06.name,reason:'Agree to the reviewed request and quotation.',acknowledged:true};
s.selectPlan('A');
assert.throws(()=>s.assignSupport(),/TASKS_REQUIRED/);
assert.throws(()=>s.designateApprover(),/TASKS_REQUIRED/);
s.saveDrafts({technical:'Review scope.',quality:'Review evidence.',budget:'Review quotation.'});s.confirmTasks();
s.assignSupport();s.designateApprover();
assert.equal(s.getState().clock,d.initialClock);
assert.equal(s.getState().decision.support.acceptedAt,null,'Designation does not require or fabricate Ben acceptance');
for(const id of ['backupAssigned','alternateAssigned']) assert.equal(s.getState().decision.audit.find(r=>r.id===id).at,d.initialClock);
for(const id of ['P05','P06']) assert.equal(w.notifications(d,s.getState(),id)[0].at,d.initialClock,'Notification receipt uses the actual assignment');
assert.equal(w.project(d,s.getState()).records.assignBen.timing.at,d.events.backupAssigned.at,'The reminder stays fixed');
s.setViewer('P06');assert.throws(()=>s.authorize(signature),/REVIEWS_REQUIRED/);
s.setViewer('P05');s.acceptSupport();assert.throws(()=>s.authorize(signature),/ROLE_NOT_ALLOWED/);
s.setViewer('P02');s.startReview('technical');s.setViewer('P03');s.startReview('quality');
assert.equal(s.getAdvanceInfo().nextEvent,'reviewsComplete','No advance to assignment or designation deadlines');
assert.throws(()=>s.completeReview('quality','Agree.','approved'),/TOO_EARLY/,'Actual review results still need to arrive');
s.advanceNext();
s.setViewer('P02');s.completeReview('technical','Agree.','approved');s.setViewer('P03');s.completeReview('quality','Agree.','approved');
assert.equal(w.project(d,s.getState()).budgetReadyAt,d.events.reviewsComplete.at);
assert.equal(s.getAdvanceInfo().blockKey,'authorizeCustomer');
s.setViewer('P06');s.authorize(signature);
assert.equal(s.getState().decision.authorization.at,d.events.reviewsComplete.at,'No wait for the old authorization fixture');
assert.equal(s.getState().decision.authorization.budgetReviewStartedAt,s.getState().clock,'No future budget start is fabricated');
assert.equal(w.notifications(d,s.getState(),'P07').find(n=>n.kind==='authorizationReceived').at,s.getState().clock);
s.setViewer('P07');s.startResourceReview();
assert.equal(s.getAdvanceInfo().nextEvent,'resourceConfirmed','External resource-result time stays fixed');
s.advanceNext();s.setViewer('P08');s.respondScheduling({outcome:'unavailable',reason:'Laboratory slots cannot be arranged.'});
s.setViewer('P07');s.returnResourceReceipt();s.requestReschedule();
assert.equal(s.getState().decision.resource.rescheduleRequest.at,d.events.resourceConfirmed.at,'Enquiry is immediate, not locked to the planned Monday action');
s.advanceNext();s.setViewer('P08');s.respondRescheduleQuote();s.setViewer('P07');s.returnRescheduleQuote();
const returned=s.getState().clock;
assert.equal(s.getAdvanceInfo().nextEvent,'rescheduleCustomerAvailable','Guide offers a daytime handoff');
s.setViewer('P01');s.createRescheduleDecision();s.setViewer('P06');s.authorizeReschedule(signature);
assert.equal(s.getState().clock,returned,'Manual early decisions are allowed, independent of the guide’s suggested calendar');
s.setViewer('P07');assert.throws(()=>s.confirmReschedule(),/TOO_EARLY/,'Actual resource confirmation still waits for the external result');
s.advanceNext();s.confirmReschedule();
assert.equal(w.project(d,s.getState()).rescheduleFees,d.fees.reschedule);
const late=core.createSession(d);late.advanceTo('latestAuthorization');late.selectPlan('A');late.saveDrafts({technical:'Review.',quality:'Review.',budget:'Review.'});late.confirmTasks();late.assignSupport();late.designateApprover();
assert.equal(late.getState().decision.support.assignedAt,late.getState().clock,'Missing a reminder does not disable the task');
assert.equal(JSON.stringify(d),frozen);
console.log('Action timing checks passed: early and late actions, independent designation, actual notifications and handoffs, prerequisite guards, guide skips, fixed external results and immutable dates/fees.');
