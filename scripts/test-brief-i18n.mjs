import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import vm from 'node:vm';
import assert from 'node:assert/strict';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const context = { Intl, Date };
for (const file of ['src/data.js', 'src/locales/en.js', 'src/locales/zh.js', 'src/locales/brief-en.js', 'src/locales/brief-zh.js', 'src/core.js', 'src/workflow.js', 'src/brief.js', 'src/brief-view.js']) vm.runInNewContext(readFileSync(path.join(root, file), 'utf8'), context);
const { DEMO_DATA: data, DEMO_CORE: core, DEMO_BRIEF: model, DEMO_BRIEF_VIEW: view, DEMO_MESSAGES: messages } = context;
const session = core.createSession(data);
const fixtures = { drafts: {technical:'测试技术范围',quality:'测试质量范围',budget:'测试预算范围'}, reviewReasons: {technical:'同意小试范围',quality:'同意证据要求'}, authorizationReason:'授权所列范围' };
const escape = value => String(value).replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;');
const counts = {};
const snapshot = () => JSON.stringify(session.getState());
function generated() {
  const before = snapshot();
  const en = model.generate({data,core,state:session.getState(),text:messages.en});
  const zh = model.localize(en,messages.zh);
  assert.equal(snapshot(),before,'Rendering translations never changes business state');
  assert.ok(zh.content.includes('SEC-HPLC（体积排阻高效液相色谱）'));
  assert.ok(zh.content.includes('HMW（高分子量组分）'));
  assert.ok(zh.content.includes('2.8%') && zh.content.includes('2.0%'));
  assert.ok(zh.metadata.asOf.includes('纽约'));
  assert.equal(zh.content.split('\n').filter(line=>line.startsWith('- ')).length,3);
  assert.equal((model.copyText(zh,messages.zh).match(/本案设计假设/g)||[]).length,1);
  assert.equal((model.copyText(zh,messages.zh).match(/不是交付承诺/g)||[]).length,1);
  assert.equal(model.localize(zh,messages.en).content,en.content);
  assert.equal(JSON.stringify(zh.snapshot),JSON.stringify(en.snapshot));
  assert.deepEqual([...zh.metadata.sourceVersions],[...en.metadata.sourceVersions]);
  assert.deepEqual(zh.content.match(/\$[\d,]+/g),en.content.match(/\$[\d,]+/g),'Both languages use the same amount sequence');
  const english = zh.content.match(/[A-Za-z][A-Za-z -]{3,}/g)||[];
  for (const token of english) assert.ok(Object.values(data.people).some(person=>person.name===token.trim()) || /^(?:SEC-HPLC|HMW|GMP|QA|Alex(?: Lin)?|Emma|Elena|IND|CMC|DS|HBT-|EXP-|SEC-)$/.test(token.trim()),`Unexpected English prose in ${zh.statusKey}: ${token}`);
  const count = model.wordCount(zh,messages.zh);
  assert.ok(count >= 250 && count <= 750,`${zh.statusKey}: ${count} Chinese units; keep a concise one-page brief`);
  counts[zh.statusKey] = count;
  const table = /<table[\s>]/.test(view.renderMarkdown(zh.content));
  assert.equal(table,zh.statusKey==='beforeAuthorization');
  return zh;
}
let brief=generated();
assert.match(brief.content,/2026年11月13日（周五）\s*17:00 纽约/);
assert.match(brief.content,/比需求早 8 天/);
assert.match(brief.content,/比需求晚 34 天/);

session.enterChapter('authorization',fixtures);session.setViewer('P01');
let draft=generated();draft.previewed=true;
const v1=model.attach({brief:draft,attachments:[],data,core,state:session.getState()});
const frozen=JSON.stringify(v1);
const english=model.localize(draft,messages.en);
assert.ok(model.isAttachedDraft(english,v1),'A display-language switch is not a new attachment');
assert.strictEqual(model.attach({brief:english,attachments:[v1],data,core,state:session.getState()}),v1);
assert.equal(JSON.stringify(v1),frozen,'A frozen attachment remains byte-for-byte unchanged');
const edited={...draft,content:draft.content+'\n\nEmma 的补充：请关注工艺就绪评估。',edited:true,previewed:true};
const editedEnglish=model.localize(edited,messages.en);
assert.equal(editedEnglish.content,edited.content,'User-authored content is retained verbatim');
assert.equal(editedEnglish.authoredLanguage,'zh');
assert.ok(model.copyText(editedEnglish,messages.en).includes('Emma 的补充'));
const v2=model.attach({brief:editedEnglish,attachments:[v1],data,core,state:session.getState()});
assert.equal(v2.version,2);
session.setViewer('P06');session.authorize({signature:data.people.P06.name,reason:'同意此次小试和资源范围',acknowledged:true,briefAttachment:v2});
const signature=JSON.stringify(session.getState().decision.authorization);
const html=view.render({brief:edited,attachment:v2,attachments:[v1,v2],state:session.getState(),text:messages.zh,helpers:{escape,requestTime:at=>core.formatInstant(at,data.baseline.timezone,{locale:'zh-CN'})+' 纽约'}});
assert.ok(html.includes('已被 v2 替代') && html.includes('只读'));
assert.ok(!html.includes('management-brief-editor'));
assert.ok(html.includes('Emma 的补充'));
assert.equal(JSON.stringify(session.getState().decision.authorization),signature);
session.setViewer('P01');generated();

session.enterChapter('hold',fixtures);session.setViewer('P07');session.startResourceReview();session.advanceNext();session.setViewer('P08');session.respondScheduling({outcome:'held',reason:'确认所列资源与暂留范围'});session.setViewer('P07');session.returnResourceReceipt();session.setViewer('P01');
brief=generated();
assert.match(brief.content,/已授权 \$80,000.*已产生 \$50,000/);
assert.match(brief.content,/\$30,000 追加小试尚未开始/);
assert.ok(!brief.content.includes('$40,000'));
assert.match(brief.content,/2026年12月9日（周三）\s*17:00 上海/);

session.enterChapter('unavailable',fixtures);session.respondScheduling({outcome:'unavailable',reason:'无法安排加急实验及配套分析时段'});session.setViewer('P07');session.returnResourceReceipt();session.setViewer('P01');generated();
session.setViewer('P07');session.advanceTo('rescheduleRequested');session.requestReschedule();session.setViewer('P01');generated();
session.setViewer('P08');session.advanceTo('rescheduleQuotePrepared');session.respondRescheduleQuote();session.setViewer('P07');session.advanceTo('rescheduleQuoteReturned');session.returnRescheduleQuote();session.setViewer('P01');generated();
session.advanceTo('rescheduleDecisionCreated');session.createRescheduleDecision();generated();
session.setViewer('P06');session.advanceTo('rescheduleAuthorized');session.authorizeReschedule({signature:data.people.P06.name,reason:'仅授权改期费',acknowledged:true});session.setViewer('P01');generated();
session.setViewer('P07');session.advanceTo('rescheduleConfirmed');session.confirmReschedule();session.setViewer('P01');brief=generated();
assert.match(brief.content,/2027年2月15日 上海.*已产生 \$10,000 改期费/);
assert.ok(!brief.content.includes('$40,000')&&!brief.content.includes('$80,000'));
assert.ok(brief.content.includes('单独授权的改期'));
assert.ok(brief.content.includes('技术重评估状态'));
console.log('Brief i18n checks passed: all states use shared values, Chinese dates and concise native summaries; switching languages preserves frozen snapshots, authored text and signed attachment basis.',counts);
