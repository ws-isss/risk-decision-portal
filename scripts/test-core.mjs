import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import vm from 'node:vm';
import assert from 'node:assert/strict';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const context = { Intl, Date };
for (const file of ['src/data.js', 'src/core.js']) vm.runInNewContext(readFileSync(path.join(root, file), 'utf8'), context);
const { DEMO_DATA: d, DEMO_CORE: c } = context;
assert.equal(c.calendarGap(d.baseline.needByLocalDate, d.plans.A.forecast.localDate), 8);
assert.equal(c.calendarGap(d.baseline.needByLocalDate, d.plans.B.forecast.localDate), -34);
assert.equal(c.calendarGap('2027-03-15', '2027-03-13'), 2, 'DST must not change local calendar-day gaps');
assert.equal(c.calendarGap('2027-03-11', '2027-03-11'), 0);
assert.equal(c.validLocalDate('2027-02-29'), false);
assert.equal(c.validLocalDate('2028-02-29'), true);
assert.throws(() => c.calendarGap('', '2027-03-11'), /INVALID_LOCAL_DATE/);
assert.match(c.formatInstant(d.plans.A.forecast.delivery, 'Asia/Shanghai'), /Mar 12.*6:00 AM/);
assert.match(c.formatInstant(d.plans.B.forecast.delivery, 'Asia/Shanghai'), /Apr 23.*5:00 AM/);
const session = c.createSession(d);
const baseline = session.getState();
session.setViewer('P07');
assert.equal(session.getState().clock, baseline.clock, 'Role changes must not move time');
assert.equal(session.getState().revision, baseline.revision, 'View changes must not mark source content changed');
session.setRequirement({ needByLocalDate: '2027-03-10', deliverableOverride: '', destinationOverride: '' });
assert.equal(c.calendarGap(session.getState().needByLocalDate, d.plans.A.forecast.localDate), -1);
assert.equal(d.baseline.needByLocalDate, '2027-03-19');
assert.equal(d.plans.A.forecast.localDate, '2027-03-11');
assert.equal(session.getState().clock, baseline.clock);
assert.equal(session.getState().revision, baseline.revision + 1);
session.advanceTo('reviewsComplete');
const progressed = session.getState();
session.advanceTo('reviewsComplete');
assert.equal(session.getState().eventIds.length, 0, 'Clock changes must not record completed business events');
assert.equal(session.getState().revision, progressed.revision, 'Repeating the same clock change is idempotent');
assert.throws(() => session.advanceTo('backupAssigned'), /CLOCK_CANNOT_REWIND/);
assert.equal(session.getState().clock, progressed.clock);
session.setViewer('P01');
assert.equal(session.getState().clock, progressed.clock);
session.reset('customer');
assert.equal(session.getState().clock, baseline.clock);
assert.equal(session.getState().needByLocalDate, baseline.needByLocalDate);
assert.equal(session.getState().resetNotice, true, 'Rewind must carry a reset notice');
session.reset('prepublication');
assert.equal(session.getState().clock, d.events.riskDiscovered.at);
assert.equal(session.getState().resetNotice, true);
assert.throws(() => session.setViewer('unknown'), /UNKNOWN_VIEWER/);
console.log('Core checks passed: calendar gaps, DST display, frozen forecasts, source revisions, monotonic clock, idempotency and explicit reset.');
