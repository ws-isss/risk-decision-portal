function completePlan(plan, fallback) {
  const session = core.createSession(data);
  session.selectPlan(plan); if (fallback) session.setFallback(true);
  session.saveDrafts(drafts); session.confirmTasks();
  session.setViewer('P02'); session.startReview('technical');
  session.setViewer('P03'); session.startReview('quality'); session.advanceTo('backupAssigned');
  session.setViewer('P01'); session.assignSupport();
  session.setViewer('P05'); session.acceptSupport(); session.advanceTo('alternateAssigned');
  session.setViewer('P01'); session.designateApprover(); session.advanceTo('reviewsComplete');
  session.setViewer('P02'); session.completeReview('technical', 'Technical opinion', 'approved');
  session.setViewer('P03'); session.completeReview('quality', 'Quality opinion', 'approved'); session.advanceTo('budgetAuthorized');
  session.setViewer('P06'); session.authorize(signature);
  return session;
}
assert.equal(completePlan('B', false).getState().decision.authorization.total, data.fees.totals.B);
const fallback = completePlan('A', true).getState().decision.authorization;
assert.equal(fallback.total, data.fees.totals.AWithFallback);
assert.equal(fallback.fallbackCap, data.fees.fallbackCap);
assert.ok(fallback.total <= data.people.P06.budgetLimit);

